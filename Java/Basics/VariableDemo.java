class VariableDemo 
{
    public static void main(String[] args)
    {
        int a=20;
        float f=10.5f;
        double d=99.9;
        char c = 'A';
        boolean b= false;
        String s="Variable demo";
        System.out.println("The Value of Integer" +a);
        System.out.println("The Value of float" +f);
        System.out.println("The Value of double" +d);
        System.out.println("The Value of character" +c);
        System.out.println("The Value of Boolean" +b);
        System.out.println("The Value of string" +s);
        
    }
}
